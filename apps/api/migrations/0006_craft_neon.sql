-- ── Неон: три вида, у однотонного цвет выбирает игрок ─────────────────────
-- Было «есть / нет». Старые отметки «есть» не говорят, какой неон, поэтому
-- из объявлений они убираются (продавец укажет вид при правке).
UPDATE listings l SET attributes = l.attributes - 'neon'
FROM listing_types t
WHERE t.id = l.listing_type_id AND t.code = 'vehicle' AND jsonb_typeof(l.attributes -> 'neon') = 'boolean';

UPDATE attribute_definitions a SET
  data_type  = 'select',
  options    = ARRAY['Нет', 'Градиент', 'Радуга', 'Однотонный'],
  updated_at = now()
FROM listing_types t
WHERE t.id = a.listing_type_id AND t.code = 'vehicle' AND a.key = 'neon' AND a.data_type = 'boolean';

INSERT INTO attribute_definitions (listing_type_id, key, label, data_type, help_text, sort_order)
SELECT t.id, 'neon_color', 'Цвет неона', 'text', 'Для однотонного неона', 55
FROM listing_types t
WHERE t.code = 'vehicle'
ON CONFLICT (listing_type_id, key) DO NOTHING;
