-- Справочник предметов: одинаковые названия разрешены (в игре есть разные предметы
-- с одним названием, их различают по иконке), иконки предметов и начальное наполнение.

DROP INDEX catalog_items_name_uq;
CREATE INDEX catalog_items_category_name_idx ON catalog_items (category_id, lower(name));

-- Иконка предмета: картинка (WebP) или короткое видео (WebM), путь относительно хранилища файлов.
ALTER TABLE catalog_items
  ADD COLUMN icon_path text,
  ADD COLUMN icon_kind text CHECK (icon_kind IN ('image', 'video')),
  ADD COLUMN sort_order integer NOT NULL DEFAULT 0;

-- Категории павильонов на рынках (по скриншоту из игры). Подкатегорий в игре нет.
INSERT INTO categories (section_id, name, sort_order)
SELECT s.id, c.name, c.sort_order
FROM sections s,
  (VALUES
    ('Аксессуары', 1),
    ('Крафт', 2),
    ('Продовольствие', 3),
    ('Одежда', 4),
    ('Тюнинг', 5),
    ('Анимации', 6),
    ('Кейсы', 7),
    ('Компоненты PC', 8),
    ('Усилители', 9),
    ('Разное', 10)
  ) AS c (name, sort_order)
WHERE s.code = 'items'
  AND NOT EXISTS (
    SELECT 1 FROM categories x
    WHERE x.section_id = s.id AND x.parent_id IS NULL AND lower(x.name) = lower(c.name)
  );

